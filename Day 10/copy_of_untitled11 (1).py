def predict(input_dict):
    import pandas as pd
    import joblib

    # STEP 1 — Load all pkl files inside function
    try:
        model          = joblib.load("models/final_model.pkl")
        scaler         = joblib.load("models/scaler.pkl")
        label_enc      = joblib.load("models/label_encoder.pkl")
        activity_enc   = joblib.load("models/activity_encoder.pkl")
        feature_cols   = joblib.load("models/feature_columns.pkl")
        top_features   = joblib.load("models/top_features.pkl")
    except Exception as e:
        return {"error": f"Failed to load model files: {str(e)}"}

    # STEP 2 — Validate inputs
    for field in feature_cols:
        if field not in input_dict:
            return {"error": f"Missing field: '{field}'"}

    if input_dict.get('activity_type') not in list(activity_enc.classes_):
        return {"error": f"activity_type must be one of {list(activity_enc.classes_)}"}

    try:
        if float(input_dict.get('heart_rate', 0)) < 0:
            return {"error": "heart_rate cannot be negative"}
    except (ValueError, TypeError):
        return {"error": "heart_rate must be a number"}

    # STEP 3 — Convert dict to DataFrame
    try:
        input_df = pd.DataFrame([input_dict])
        input_df['activity_type'] = activity_enc.transform(input_df['activity_type'])
        input_df = input_df[feature_cols]
    except Exception as e:
        return {"error": f"Data preparation failed: {str(e)}"}

    # STEP 4 — Scale and Predict
    try:
        X_scaled       = scaler.transform(input_df)
        pred_encoded   = model.predict(X_scaled)[0]
        pred_proba     = model.predict_proba(X_scaled)[0]
        confidence_pct = round(max(pred_proba) * 100, 1)
    except Exception as e:
        return {"error": f"Prediction failed: {str(e)}"}

    # STEP 5 — Return clean dict
    prediction_label = label_enc.inverse_transform([pred_encoded])[0]

    return {
        "prediction"  : prediction_label,
        "confidence"  : f"{confidence_pct}%",
        "top_features": top_features,
        "risk_level"  : prediction_label
    }

