def assign_risk(row):
    score = 0
    if row['heart_rate'] > 100 or row['heart_rate'] < 50:
        score += 2
    if row['spo2_level'] < 94:
        score += 2
    if row['blood_pressure_sys'] > 140 or row['blood_pressure_sys'] < 90:
        score += 2
    if row['blood_glucose'] > 180 or row['blood_glucose'] < 70:
        score += 1
    if row['body_temperature'] > 38.0 or row['body_temperature'] < 35.5:
        score += 1
    if row['respiration_rate'] > 20 or row['respiration_rate'] < 10:
        score += 1
    if row['fall_detected'] == 1:
        score += 2
    if row['stress_level_index'] > 70:
        score += 1

    if score <= 1:
        return 'Low'
    elif score <= 4:
        return 'Medium'
    else:
        return 'High'

